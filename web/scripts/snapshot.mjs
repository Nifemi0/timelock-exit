#!/usr/bin/env node
/**
 * Build web/public/history.json: every event the app needs, up to a recent block.
 *
 * Public RPCs cap eth_getLogs ranges (Base Sepolia PublicNode: 50,000 blocks; Reactive
 * Lasna: 30,000), and free indexers rate-limit, so the app cannot rebuild history on every
 * page load. This script does it once, incrementally from the previous snapshot, and the
 * app only scans the blocks after it. Run it after queueing a change, then commit.
 *
 * Usage: node web/scripts/snapshot.mjs   (no dependencies; Node 18+)
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const OUT = join(here, '..', 'public', 'history.json')

const BASE_RPC = process.env.BASE_RPC || 'https://base-sepolia-rpc.publicnode.com'
const LASNA_RPC = process.env.LASNA_RPC || 'https://lasna-rpc.rnk.dev/'
const BASE_CHUNK = 50_000
const LASNA_CHUNK = 30_000

// Public deployment addresses (15 Nov 2026) and the blocks just before they were created.
const TIMELOCK = '0x65503cE4DeC92399b0d1dc08e2b53fc47c03901e'
const EXIT_GUARD = '0x85703e534Fd619eE55484D59259F84fC0340Cd2a'
const SENTINEL = '0xa00b864fFBC6992195fFB649F5BC36a50fBD6D59'
const BASE_FROM = 59_288_000
const LASNA_FROM = 8_440_000
// keccak256("ExitRequested(address,bytes32,address,address,address,bytes4,uint256)")
const EXIT_REQUESTED = '0x74115657f008d6854b68cc5a81f8bad6e1e4c8675f05c1a87ddffaadbb580e9c'

let id = 0
async function rpc(url, method, params, attempt = 0) {
  let failure
  try {
    const res = await fetch(url, {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({ jsonrpc: '2.0', id: ++id, method, params }),
    })
    const body = await res.json().catch(() => ({}))
    if (body.result !== undefined) return body.result
    failure = body.error ?? `HTTP ${res.status}`
  } catch (err) {
    failure = err.cause?.code ?? err.message // network errors (DNS, reset) are retried too
  }
  if (attempt < 5) {
    await new Promise(r => setTimeout(r, 2000 * (attempt + 1)))
    return rpc(url, method, params, attempt + 1)
  }
  throw new Error(`${method} failed after retries: ${JSON.stringify(failure)}`)
}

const hex = n => '0x' + n.toString(16)

async function logs(url, address, from, to, chunk, topics) {
  const out = []
  for (let start = from; start <= to; start += chunk) {
    const end = Math.min(start + chunk - 1, to)
    const filter = { address, fromBlock: hex(start), toBlock: hex(end) }
    if (topics) filter.topics = topics
    out.push(...(await rpc(url, 'eth_getLogs', [filter])))
  }
  return out
}

async function timestamps(url, blockNumbers) {
  const times = {}
  for (const n of [...new Set(blockNumbers)]) {
    const block = await rpc(url, 'eth_getBlockByNumber', [n, false])
    times[n] = parseInt(block.timestamp, 16)
  }
  return times
}

const slim = (l, ts) => ({
  topics: l.topics,
  data: l.data,
  blockNumber: l.blockNumber,
  transactionHash: l.transactionHash,
  logIndex: l.logIndex,
  timestamp: ts,
})

const key = l => `${l.transactionHash}:${l.logIndex}`
function merge(previous = [], fresh = []) {
  const seen = new Map(previous.map(l => [key(l), l]))
  for (const l of fresh) seen.set(key(l), l)
  return [...seen.values()].sort((a, b) => parseInt(a.blockNumber, 16) - parseInt(b.blockNumber, 16))
}

async function main() {
  const prev = existsSync(OUT) ? JSON.parse(readFileSync(OUT, 'utf8')) : null

  // Stop a little short of the head so a reorg near the tip cannot leave a stale entry.
  const baseHead = parseInt(await rpc(BASE_RPC, 'eth_blockNumber', []), 16) - 50
  const lasnaHead = parseInt(await rpc(LASNA_RPC, 'eth_blockNumber', []), 16) - 20
  const baseFrom = prev ? prev.base.toBlock + 1 : BASE_FROM
  const lasnaFrom = prev ? prev.lasna.toBlock + 1 : LASNA_FROM

  console.log(`Base Sepolia ${baseFrom} -> ${baseHead}; Lasna ${lasnaFrom} -> ${lasnaHead}`)

  const [tl, eg] = await Promise.all([
    logs(BASE_RPC, TIMELOCK, baseFrom, baseHead, BASE_CHUNK),
    logs(BASE_RPC, EXIT_GUARD, baseFrom, baseHead, BASE_CHUNK),
  ])
  const ts = await timestamps(BASE_RPC, [...tl, ...eg].map(l => l.blockNumber))
  const reqs = await logs(LASNA_RPC, SENTINEL, lasnaFrom, lasnaHead, LASNA_CHUNK, [EXIT_REQUESTED])
  const lts = await timestamps(LASNA_RPC, reqs.map(l => l.blockNumber))

  const snapshot = {
    note: 'Generated by web/scripts/snapshot.mjs. Event history up to the listed blocks; the app scans the rest live.',
    generatedAt: new Date().toISOString(),
    base: {
      toBlock: baseHead,
      logs: {
        [TIMELOCK.toLowerCase()]: merge(prev?.base.logs[TIMELOCK.toLowerCase()], tl.map(l => slim(l, ts[l.blockNumber]))),
        [EXIT_GUARD.toLowerCase()]: merge(prev?.base.logs[EXIT_GUARD.toLowerCase()], eg.map(l => slim(l, ts[l.blockNumber]))),
      },
    },
    lasna: {
      toBlock: lasnaHead,
      exitRequested: merge(prev?.lasna.exitRequested, reqs.map(l => slim(l, lts[l.blockNumber]))),
    },
  }

  writeFileSync(OUT, JSON.stringify(snapshot, null, 1) + '\n')
  const n = Object.values(snapshot.base.logs).reduce((s, v) => s + v.length, 0)
  console.log(`Wrote ${OUT}: ${n} Base logs, ${snapshot.lasna.exitRequested.length} Lasna exit requests`)
}

main().catch(err => {
  console.error(err)
  process.exit(1)
})
